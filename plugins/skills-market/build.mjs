/**
 * Build step for the skills market.
 *
 * Concatenates the pure model, the React UI, and the entry into one classic
 * script for `window.__ModuleLoader__`. The locale files are inlined here so
 * the browser bundle never fetches JSON: `meta` stays in the files for the
 * marketplace listing and is not registered as a dictionary entry.
 *
 * Run: node build.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const read = (path) => readFileSync(join(here, path), 'utf8')
const stripExports = (source) => source.replace(/^export\s+/gmu, '')

/**
 * Read one locale file and return its message dictionary without `meta`.
 * @param locale - `zh` or `en`.
 * @returns the dictionary.
 */
function readDictionary(locale) {
  const document = JSON.parse(read(join('locale', `${locale}.json`)))
  if (document === null || typeof document !== 'object' || Array.isArray(document)) {
    throw new Error(`locale/${locale}.json must be a JSON object`)
  }
  const { meta, ...dictionary } = document
  if (meta === undefined) throw new Error(`locale/${locale}.json is missing meta`)
  for (const [key, value] of Object.entries(dictionary)) {
    if (typeof value !== 'string' || value === '') {
      throw new Error(`locale/${locale}.json: "${key}" must be a non-empty string`)
    }
  }
  return dictionary
}

const dictionaries = {
  zh: readDictionary('zh'),
  en: readDictionary('en'),
}
const zhKeys = Object.keys(dictionaries.zh).sort()
const enKeys = Object.keys(dictionaries.en).sort()
if (zhKeys.join('\n') !== enKeys.join('\n')) {
  const missingInEn = zhKeys.filter((key) => !enKeys.includes(key))
  const missingInZh = enKeys.filter((key) => !zhKeys.includes(key))
  throw new Error(`locale keys differ (missing in en: ${missingInEn.join(', ') || 'none'}; missing in zh: ${missingInZh.join(', ') || 'none'})`)
}

const model = stripExports(read(join('src', 'model.mjs')))
const ui = read(join('src', 'ui.js'))
const entry = stripExports(read(join('src', 'entry.js')))

for (const [name, source] of [['model.mjs', model], ['ui.js', ui], ['entry.js', entry]]) {
  if (/^\s*(?:import|export)\s/mu.test(source)) {
    throw new Error(`${name} still contains a top-level import/export`)
  }
}

const localesSource = JSON.stringify(dictionaries, null, 2)
  .split('\n')
  .map((line, index) => (index === 0 ? line : `    ${line}`))
  .join('\n')

const output = `/**
 * GENERATED by build.mjs. Edit src/*.js|mjs or locale/*.json, then run
 * \`node build.mjs\`.
 *
 * @hongxsen/dsh-skills-market — browser half.
 *
 * Search skills.sh through the Host, preview every file and safety warning,
 * install into ~/.dsh/skills, and manage installed skills from a full-page
 * sidebar panel.
 */
window.__ModuleLoader__.load({
  id: '@hongxsen/dsh-skills-market',
  factory(require) {
    const React = require('react')

    const LOCALES = ${localesSource}

${model}

${ui}

${entry}

    return { inject, apply }
  },
})
`

if (output.includes('@@')) throw new Error('client.js still contains an unreplaced placeholder')
writeFileSync(join(here, 'client.js'), output)
console.log(`client.js written (${output.length.toLocaleString()} bytes, ${zhKeys.length} locale keys)`)
