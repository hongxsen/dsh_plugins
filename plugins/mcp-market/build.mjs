/**
 * Build the browser bundle.
 *
 * The client loader evaluates `client.js` as a classic script and hands the
 * factory a `require` for host modules, so the bundle cannot keep ES module
 * syntax. This script inlines the pure model (dropping `export` prefixes), the
 * React UI, the entry, and both locale dictionaries.
 *
 * Run: node build.mjs
 */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const read = name => readFile(join(here, name), 'utf8')
const stripExports = source => source.replace(/^export\s+/gmu, '')

/** Flatten nested dictionary keys so zh and en cannot drift. */
function keyPaths(value, prefix = '') {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) return [prefix]
  return Object.keys(value).flatMap(key => keyPaths(value[key], prefix === '' ? key : `${prefix}.${key}`))
}

async function main() {
  const zh = JSON.parse(await read('locale/zh.json'))
  const en = JSON.parse(await read('locale/en.json'))
  const zhKeys = keyPaths(zh).sort()
  const enKeys = keyPaths(en).sort()
  if (zhKeys.join('\n') !== enKeys.join('\n')) {
    throw new Error('locale/zh.json and locale/en.json do not declare the same keys')
  }
  if (typeof zh.meta?.title !== 'string' || typeof en.meta?.title !== 'string') {
    throw new Error('locale files must declare meta.title')
  }
  // `meta` is marketplace card metadata, not a UI message. The locale runtime
  // stores every key as a string, so keep it out of the registered dictionary.
  const dictionaries = {
    zh: Object.fromEntries(Object.entries(zh).filter(([key]) => key !== 'meta')),
    en: Object.fromEntries(Object.entries(en).filter(([key]) => key !== 'meta')),
  }

  const sources = {
    'model.mjs': stripExports(await read('src/model.mjs')),
    'ui.js': await read('src/ui.js'),
    'entry.js': stripExports(await read('src/entry.js')),
  }
  for (const [name, source] of Object.entries(sources)) {
    if (/^\s*(?:import|export)\s/mu.test(source)) {
      throw new Error(`${name} still contains a top-level import/export`)
    }
  }

  const output = `/**
 * GENERATED by build.mjs. Edit src/*.js|mjs, then run \`node build.mjs\`.
 *
 * @hongxsen/dsh-mcp-market — official MCP registry browser for the DSH sidebar.
 *
 * Search, inspect, and install MCP servers as managed
 * @deepseek-ai/dsh-mcp-client rows in the active profile.
 */
window.__ModuleLoader__.load({
  id: '@hongxsen/dsh-mcp-market',
  factory(require) {
    const React = require('react')
    const LOCALES = ${JSON.stringify(dictionaries)}

${sources['model.mjs']}

${sources['ui.js']}

${sources['entry.js']}

    return { inject, apply }
  },
})
`

  if (output.includes('@@')) throw new Error('client.js still contains an unreplaced placeholder')
  await writeFile(join(here, 'client.js'), output)
  console.log(`client.js written (${output.length.toLocaleString()} B)`)
}

await main()
