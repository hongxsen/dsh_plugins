/**
 * Bundle `src/` into the single browser file DSH loads.
 *
 * The client loader evaluates `client.js` as a plain script and hands the
 * factory a `require` for host modules, so the bundle cannot keep ES module
 * syntax. This script inlines the pure core (dropping its `export` prefixes),
 * the DOM/React UI, and the entry object.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const read = name => readFileSync(join(here, 'src', name), 'utf8')

const core = read('core.mjs').replace(/^export\s+/gmu, '')
const ui = read('ui.js')
const entry = read('entry.js')

for (const [name, source] of [['core.mjs', core], ['ui.js', ui], ['entry.js', entry]]) {
  if (/^\s*(?:import|export)\s/mu.test(source)) {
    throw new Error(`${name} still contains a top-level import/export`)
  }
}

const output = `/**
 * GENERATED by build.mjs. Edit src/*.js|mjs, then run \`node build.mjs\`.
 *
 * @hongxsen/dsh-co-write — 人机双写
 *
 * Picks material from the loaded conversation, workspace files, or free text,
 * annotates it, and submits the result as the next message.
 */
window.__ModuleLoader__.load({
  id: '@hongxsen/dsh-co-write',
  factory(require) {
    const React = require('react')

${core}

${ui}

${entry}

    return { inject, apply }
  },
})
`

writeFileSync(join(here, 'client.js'), output)
console.log(`client.js written (${output.length.toLocaleString()} bytes)`)
